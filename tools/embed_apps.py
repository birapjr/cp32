"""Generate the optional, SRAM-resident application update payload."""
from pathlib import Path
import sys
names=('hello','echo','cat','wc','ls','exec')
folder=Path(sys.argv[1]);out=Path(sys.argv[2])
lines=['/* Generated by embed_apps.py; updater builds only. */']
for name in names:
 data=(folder/(name+'.elf')).read_bytes()
 # File size includes both load segments and ELF headers. The linker/loader
 # independently enforce 16 KiB code and 12 KiB data; SRAM is link-checked.
 if data[:7]!=b'\x7fELF\x01\x01\x01' or len(data)>32768:
  raise ValueError('invalid/oversized application: '+name)
 lines.append('static const unsigned char payload_'+name+'[]={')
 for i in range(0,len(data),24):lines.append(','.join(str(b) for b in data[i:i+24])+',')
 lines.append('};')
lines.append('static const struct cp32_update_entry cp32_update_entries[]={')
for name in names:lines.append('{"/boot/'+name+'",payload_'+name+',sizeof(payload_'+name+')},')
lines.append('};')
out.write_text('\n'.join(lines)+'\n')
